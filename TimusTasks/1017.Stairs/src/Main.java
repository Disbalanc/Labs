import java.math.BigInteger;
import java.util.Scanner;

//1017. Лестницы
//Ограничение времени: 1.0 секунды
//Ограничение памяти: 64 МБ
//У маленького мальчика есть набор из N кубиков. Из этих кубиков можно сложить различные лестницы. Лестницы имеют ступени различного размера, следующие в порядке возрастания этого размера (обратите особое внимание на то, что лестница не может иметь две одинаковые ступени). Каждая лестница должна иметь минимум две ступени, и каждая ступень должна состоять минимум из одного кубика. На рисунке приведены примеры лестниц для N=11 и N=5:
//Problem illustration
//Найдите число Q различных лестниц, которые маленький мальчик может построить ровно из N кубиков.
//        Исходные данные
//Число N (5 ≤ N ≤ 500).
//Результат
//Число Q

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int N = scanner.nextInt();

        // dp[i] будет хранить количество разбиений числа i на различные части
        BigInteger[] dp = new BigInteger[N + 1];
        for (int i = 0; i <= N; i++) {
            dp[i] = BigInteger.ZERO;
        }
        dp[0] = BigInteger.ONE; // база: пустое разбиение

        // Классический алгоритм для разбиений на различные части:
        // для каждой возможной части j от 1 до N
        // обновляем dp[i] в обратном порядке, чтобы каждая часть использовалась не более одного раза
        for (int j = 1; j <= N; j++) {
            for (int i = N; i >= j; i--) {
                dp[i] = dp[i].add(dp[i - j]);
            }
        }

        // Ответ: все разбиения на различные части минус одно (разбиение из одной части - саму лестницу из одной ступени)
        BigInteger result = dp[N].subtract(BigInteger.ONE);
        System.out.println(result);

        scanner.close();
    }
}