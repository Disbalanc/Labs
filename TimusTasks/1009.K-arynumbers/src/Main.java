import java.util.Scanner;

//1009. K-ичные числа
//Ограничение времени: 0.5 секунды
//Ограничение памяти: 64 МБ
//Рассмотрим N-значные числа в системе счисления с основанием K. Будем считать число правильным, если его K-ичная запись не содержит двух подряд идущих нулей. Например:
//        1010230 — правильное 7-значное число;
//1000198 не является правильным числом;
//0001235 — не 7-значное, а 4-значное число.
//Даны числа N и K, вычислите количество правильных K-ичных чисел, состоящих из N цифр.
//        Ограничения: 2 ≤ K ≤ 10; N ≥ 2; N + K ≤ 18.
//Исходные данные
//Числа N и K в десятичной записи, разделенные переводом строки.
//        Результат
//Искомое количество в десятичной записи.

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);

        // Чтение входных данных
        int N = scanner.nextInt();
        int K = scanner.nextInt();

        // Динамическое программирование
        // dp[i][0] - количество чисел длины i, оканчивающихся на 0
        // dp[i][1] - количество чисел длины i, оканчивающихся не на 0
        long[][] dp = new long[N + 1][2];

        // Инициализация для чисел длины 1
        // Первая цифра не может быть 0 (иначе число не N-значное)
        dp[1][0] = 0; // Не может начинаться с 0
        dp[1][1] = K - 1; // Любая цифра от 1 до K-1

        // Заполнение таблицы
        for (int i = 2; i <= N; i++) {
            // Число, оканчивающееся на 0, может быть получено только из числа,
            // которое на предыдущем шаге оканчивалось не на 0
            dp[i][0] = dp[i - 1][1];

            // Число, оканчивающееся не на 0, может быть получено из любого числа
            // предыдущей длины, при этом добавляем любую цифру кроме 0
            dp[i][1] = (dp[i - 1][0] + dp[i - 1][1]) * (K - 1);
        }

        // Ответ: сумма всех чисел длины N (оканчивающихся на 0 и не на 0)
        long result = dp[N][0] + dp[N][1];
        System.out.println(result);

        scanner.close();
    }
}