import java.util.*;

//1039. Юбилейная вечеринка
//Ограничение времени: 0.5 секунды
//Ограничение памяти: 8 МБ
//Ректор Уральского государственного университета собирается устроить вечеринку по случаю 80-летия университета. Университет имеет иерархическую структуру сотрудников в виде дерева с корнем в ректоре. Чтобы сделать вечеринку веселой для всех присутствующих, ректор не хочет, чтобы кто-то из ее участников мог столкнуться там со своим непосредственным руководителем (это означает, что сотрудник и его непосредственный руководитель не должны быть одновременно приглашены на вечеринку).
//Отдел кадров вычислил уровень праздничного настроения каждого сотрудника университета. Ваша задача – составить список гостей с максимальным суммарным уровнем праздничного настроения, выполнив при этом условие ректора.
//        Исходные данные
//В первой строке записано целое число N – количество сотрудников университета (1 ≤ N ≤ 6000). Сотрудники пронумерованы целыми числами в диапазоне от 1 до N. Каждая из последующих N строк содержит рейтинг праздничного настроения соответствующего сотрудника – целое число в диапазоне от −128 до 127. Затем идет описание дерева структуры сотрудников. Каждая строка описания дерева имеет следующую форму
//        <L> <K>
//        это означает, что K-й сотрудник является непосредственным руководителем L-го сотрудника. Ввод заканчивается строкой
//0 0
//Результат
//Выведите максимальный суммарный уровень праздничного настроения гостей.

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int N = scanner.nextInt();
        int[] weight = new int[N + 1];
        for (int i = 1; i <= N; i++) {
            weight[i] = scanner.nextInt();
        }

        // Инициализация списка детей (создаем только при необходимости)
        List<Integer>[] children = new List[N + 1];
        boolean[] hasParent = new boolean[N + 1];

        // Чтение пар "подчиненный руководитель" до "0 0"
        while (true) {
            int L = scanner.nextInt();
            int K = scanner.nextInt();
            if (L == 0 && K == 0) {
                break;
            }
            if (children[K] == null) {
                children[K] = new ArrayList<>();
            }
            children[K].add(L);
            hasParent[L] = true;
        }

        // Находим корень (вершину без родителя)
        int root = 0;
        for (int i = 1; i <= N; i++) {
            if (!hasParent[i]) {
                root = i;
                break;
            }
        }

        int[] dp0 = new int[N + 1]; // максимум, если вершина не выбрана
        int[] dp1 = new int[N + 1]; // максимум, если вершина выбрана

        // Пост-порядок обхода дерева (дети раньше родителя)
        Deque<Integer> stack = new ArrayDeque<>();
        stack.push(root);
        Deque<Integer> postOrder = new ArrayDeque<>();
        while (!stack.isEmpty()) {
            int u = stack.pop();
            postOrder.push(u);
            if (children[u] != null) {
                for (int v : children[u]) {
                    stack.push(v);
                }
            }
        }

        // Обработка вершин в пост-порядке
        while (!postOrder.isEmpty()) {
            int u = postOrder.pop();
            dp0[u] = 0;
            dp1[u] = weight[u];
            if (children[u] != null) {
                for (int v : children[u]) {
                    dp0[u] += Math.max(dp0[v], dp1[v]);
                    dp1[u] += dp0[v];
                }
            }
        }

        System.out.println(Math.max(dp0[root], dp1[root]));
    }
}